/** Portada por cover_i de Open Library (más fiable que ISBN). */
function coverOl(coverId: number) {
  return `https://covers.openlibrary.org/b/id/${coverId}-L.jpg`;
}

/** Portada por volume id de Google Books. */
function coverGb(volumeId: string) {
  return `https://books.google.com/books/content?id=${encodeURIComponent(volumeId)}&printsec=frontcover&img=1&zoom=2&source=gbs_api`;
}

