export function searchCatalogBooks(query: string): SearchResult[] {
  const q = query.toLowerCase().trim();
  if (!q) {
    return [];
  }

  return CATALOG_BOOKS.filter((b) => {
    const hay = [b.title, b.creator, ...(b.aliases || [])].join(' ').toLowerCase();
    return hay.includes(q) || q.split(/\s+/).every((part) => hay.includes(part));
  }).map(({ isbn: _isbn, aliases: _a, rating: _r, synopsis: _s, ...rest }) => rest);
}

export function getCatalogBookById(id: string): CatalogBook | undefined {
  const clean = id.replace(/^(b_isbn_|b_gb_|b_)/, '');
  const legacy: Record<string, string> = {
    '9780345538376': '9780345370778',
    '9781250178602': '9781619634459',
    '9781250175096': '9781408884409',
    '9780307949486': '9780307272119',
  };
  const mapped = legacy[clean];
  if (mapped) {
    return CATALOG_BOOKS.find((b) => b.isbn === mapped);
  }
  return CATALOG_BOOKS.find(
    (b) =>
      b.id === id ||
      b.id.endsWith(clean) ||
      b.isbn === clean ||
      b.isbn.replace(/-/g, '') === clean,
  );
}

/** Libros del catálogo curado que encajan con un género de Explorar. */
export function getCatalogBooksByGenreTokens(match: (genres: string[]) => boolean): CatalogBook[] {
  return CATALOG_BOOKS.filter((b) => match(b.genres || []));
}
